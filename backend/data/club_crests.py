def crest_url_for(team_name: str) -> str:
    team_id = CLUB_CREST_IDS.get((team_name or "").strip())
    if not team_id:
        return ""
    return f"{_CREST_BASE}/{team_id}.png"


def is_club_team(team_name: str) -> bool:
    return (team_name or "").strip() in CLUB_CREST_IDS
